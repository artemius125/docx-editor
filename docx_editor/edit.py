def _off_term_error(op, term_variants):
    """В11 (находка Н69): правка класса «единое написание термина» бьёт по
    ЧУЖОЙ фразе не только на маршруте unify (В6/Н62 — «Сборка кандидата» →
    «Сборка релиз-кандидата»), но и на ЛОКАЛЬНОМ пути, когда Навигатор не
    распознал unify и правка идёт обычным _run_clusters — там защиты не было
    вовсе. term_variants — множество вариантов термина, уже посчитанное
    кодом (_variant_counts, то же самое, что строит инвентарь для промпта, —
    второй инвентарь не заводим). None — эта правка не того класса (инвентарь
    пуст/не считался), гвард выключен. Иначе: replace_text/replace_all,
    чей "old" не совпадает НИ С ОДНИМ посчитанным вариантом, трогает не
    термин, а что-то похожее рядом — отклоняется тем же путём, что и любая
    другая невалидная операция."""
    if term_variants is None or op.get("op") not in ("replace_text", "replace_all"):
        return None
    old = op.get("old")
    if not old:
        return None
    # Замер w20: точное равенство варианту рубило шесть правок, из них две
    # (c8, c12) были `done` до гварда. Инвентарь собран из якорей Навигатора и
    # цитат запроса — это БАЗОВЫЕ формы, а в документе вариант стоит с
    # окружением, которое правка как раз и меняет: «8.8» → old «8.8 млн»,
    # «Человек, который познал бесконечность» → old с круглыми скобками,
    # «Cross-encoder» → old «Cross-encoders». Операция, чей old НАКРЫВАЕТ
    # вариант целиком, трогает сам термин, а не соседнюю фразу. Порча В6/Н69
    # устроена наоборот: old («кандидата») — обрывок, не накрывающий ни один
    # вариант («релиз-кандидат», «кандидат на релиз»), и остаётся отклонённой.
    if any(v in old for v in term_variants):
        return None
    return (f'операция трогает «{old}», а это не один из вариантов термина, посчитанных в документе '
            f'({", ".join(sorted(term_variants))}) — правка класса «единое написание термина» должна '
            f'трогать ТОЛЬКО вхождения самих вариантов термина, а не похожие слова/фразы рядом')


def _collision_source(targets, written):
    """op, который записал диапазон, пересекающийся с targets, или None — тот
    же обход, что раньше делал _overlaps, но Change 2 требует не только факт
    коллизии, а и ВИНОВНИКА: текст ошибки обязан назвать более раннюю
    операцию батча, которая написала этот текст, а не просто отказать."""
    for el, s, e in targets:
        for ws, we, wop in written.get(el, []):
            if s < we and ws < e:
                return wop
    return None


def _shift_written(ranges, start, end, new_len):
    """Диапазоны батча (Ф12, дефект 2) после замены [start:end) на текст
    длины new_len в том же абзаце: что было раньше start — не двигается, что
    было не раньше end — сдвигается на дельту длины. Внутрь [start:end)
    записанный ранее диапазон попасть не может — _op_targets проверяется на
    пересечение ДО применения, поэтому операция, которая задела бы такой
    диапазон, отклоняется раньше, чем эта замена вообще случится. Каждый
    диапазон несёт op, который его записал (Change 2) — нужен для текста
    ошибки, сама логика сдвига его не касается.

    Исключение — set_text: он один допущен писать поверх диапазона батча (см.
    _apply_ops), и накрытый им целиком диапазон исчезает вместе со своим
    текстом. Сдвигать его некуда — он бы врал про чужое место."""
    delta = new_len - (end - start)
    return [(s, e, o) if e <= start else (s + delta, e + delta, o)
            for s, e, o in ranges if not (start <= s and e <= end)]


def _op_targets(doc, idx, op):
    """[(el, start, end)] — что операция replace_text/set_text/replace_all
    прочитает и заменит в ТЕКУЩЕМ тексте абзаца(-ев) ДО применения. Нужен
    дважды за вызов: сверить с written (эта же операция не должна попасть
    на диапазон, который в этом батче только что записала более ранняя
    операция), а после успешного apply — тем же списком дополнить written.
    Остальные операции (insert_after/delete/move_after/set_style/set_cell/
    create_table/normalize) текст по поиску не ищут — для них []."""
    name, old = op.get("op"), op.get("old")
    if name == "replace_text":
        el = idx.get(op.get("id"))
        el = el if el is not None and el.tag == qn("w:p") else None
        span = find._flex_span(patch._ptext(el), old) if el is not None else None
        return [(el, *span)] if span else []
    if name == "set_text":
        el = idx.get(op.get("id"))
        el = el if el is not None and el.tag == qn("w:p") else None
        return [(el, 0, len(patch._ptext(el)))] if el is not None else []
    if name == "replace_all":
        out = []
        for el in doc.element.body.iter(qn("w:p")):
            text, pos = patch._ptext(el), 0
            while True:
                span = find._flex_span(text[pos:], old)
                if span is None:
                    break
                out.append((el, pos + span[0], pos + span[1]))
                pos += span[1]
        return out
    return []


def _record_batch_write(op, targets, written):
    """Дописывает written диапазоном, который операция реально только что
    записала — targets обходятся в ОБРАТНОМ порядке: несколько вхождений в
    одном абзаце (replace_all) идут по убыванию позиции, как и сама замена в
    patch._op_replace_all, иначе сдвиг съедет не в ту сторону."""
    new_text = op["text"] if op.get("op") == "set_text" else op["new"]
    for el, start, end in reversed(targets):
        written[el] = _shift_written(written.get(el, []), start, end, len(new_text)) + [(start, start + len(new_text), op)]


def _own_output_error(op, source_op):
    """Change 2: голый отказ убивал правку — Редактор не понимал, что делать
    дальше, и на единственном ретрае обычно сдавался (ops: []), проваливая
    весь батч (Математика edit 1). Текст называет, ЧТО написала более ранняя
    операция, и даёт ровно два законных выхода: переписать её так, чтобы она
    сразу дала итоговый текст, либо процитировать в old другой, нетронутый
    кусок блока — один короткий абзац, читает его 26B модель, не лекция."""
    where = f"{op['id']}: " if op.get("id") else ""
    written_text = source_op["text"] if source_op.get("op") == "set_text" else source_op.get("new")
    return (
        f'{where}текст «{op.get("old")}», который эта операция ищет, только что написала более ранняя '
        f'операция этого же батча (она записала «{written_text}»). Редактировать собственный вывод внутри '
        f'одного батча нельзя: либо перепиши ТУ раннюю операцию так, чтобы она сразу дала нужный итоговый '
        f'текст, либо процитируй в old другой, ещё не тронутый кусок блока.'
    )


def _revert_written(text, ranges):
    """Текст элемента с диапазонами written, откатанными к old той операции,
    которая их записала — только чтобы ПРОВЕРИТЬ, стоял ли искомый текст на
    этом месте ДО более ранней записи этого же батча. Диапазон без old
    (source_op — set_text, там нет old) откатить нечем — оставляется как
    есть, реконструкция для него просто не сработает (вернёт False дальше)."""
    out, pos = [], 0
    for s, e, wop in sorted(ranges, key=lambda r: r[0]):
        old = wop.get("old")
        if old is None:
            continue
        out.append(text[pos:s])
        out.append(old)
        pos = e
    out.append(text[pos:])
    return "".join(out)


def _redundant_in_batch(op, idx, written):
    """ПАРТИЯ 1: True — операция избыточна ОТНОСИТЕЛЬНО этого же батча, её
    можно пропустить, не тратя ретрай. Два узких случая:

    (a) old == new — no-op по построению (validate это и так отклонит, но
        платить за это ретраем незачем).
    (b) old этой операции стоял в документе ДО того, как более ранняя
        операция этого же батча его переписала — written хранит, кто что
        записал (Change 2), reused здесь, а не заново. Проверяется
        реконструкцией: откатываем записи written в затронутом элементе к
        их old (_revert_written) и ищем old текущей операции ТАМ — нашёлся
        → цель уже достигнута раньше в этом же батче, «не найден» объясняется
        собственной перепиской, а не пробелом в документе.

    Не путать с _own_output_error/_collision_source: там old НАЙДЕН в
    текущем (не откатанном) тексте — он существует только благодаря свежей
    записи более ранней операции, откат его уберёт. Такая операция здесь
    вернёт False и останется жёсткой ошибкой — это и есть защищаемая
    граница (искажение вывода вместо избыточности)."""
    old, new = op.get("old"), op.get("new")
    if old is not None and "new" in op and old == new:
        return True
    if not old:
        return False
    name = op.get("op")
    if name == "replace_text":
        items = [(idx.get(op.get("id")), written.get(idx.get(op.get("id")), []))]
    elif name == "replace_all":
        items = list(written.items())
    else:
        return False
    for el, ranges in items:
        if el is None or not ranges:
            continue
        cur = patch._ptext(el)
        # old ЕСТЬ в текущем тексте — операция не избыточна, она применилась бы
        # сюда; отказ у неё по другой причине (например разрез посреди слова),
        # и её нельзя молча ронять — пусть идёт обычным путём с ретраем.
        if find._flex_span(cur, old) is not None:
            continue
        if find._flex_span(_revert_written(cur, ranges), old) is not None:
            return True
    return False


def _apply_ops(doc, idx, ops, fragment_text, request, editor, fragment_ids=None, written=None, ops_out=None,
                term_variants=None):
    """Применяет ops по очереди; на невалидной операции — один ретрай к
    Редактору с текстом ошибки (editor=None — ретрая нет, путь rule). Второй
    провал (или провал без Редактора) останавливает применение немедленно.
    Возвращает (описания применённых операций, причина отказа-или-None,
    tries) — tries=2, если к Редактору пришлось обращаться повторно
    (для журнала правки, поле "iter"), иначе 1.

    ops_out (В11, находка Н66) — необязательный список, в который, помимо
    текстовых описаний, копится СЫРОЙ op каждой успешно применённой операции
    (в порядке применения). Нужен `_trace_error`, чтобы проверять СДЕЛАННОЕ
    (какого рода операции реально применились), а не верить ярлыку `trace`
    Навигатора — описания в `applied` для этого не годятся, там только текст.

    term_variants (В11, находка Н69) — множество вариантов термина, уже
    посчитанное `_variant_counts` (тот же инвентарь, что уходит в промпт
    Редактору как «Найдено в документе: …»), или None — правка не того
    класса, гвард выключен. См. `_off_term_error`: replace_text/replace_all,
    чей "old" не входит в этот набор, отклоняется как невалидная операция —
    защита В6/Н62 («Сборка кандидата» → «Сборка релиз-кандидата») раньше
    стояла только на маршруте unify, здесь распространена на локальный путь.

    fragment_ids=None — гвард выключен (путь rule: editor=None, id-полей у
    normalize нет). Иначе — set id блоков фрагмента, который видел Редактор;
    операция вне этого множества отклоняется ДО patch.validate, тем же текстом
    ошибки и тем же единственным ретраем, что и любая другая невалидная
    операция (находка: validate звали с картой ВСЕГО документа, поэтому id
    любого существующего блока проходил, даже если Редактор его не видел).
    Успешно применённая операция пополняет fragment_ids id-ами, которые
    patch.apply мог только что создать (_register кладёт их прямо в idx) —
    иначе insert_after/create_table внутри своего же батча не смогли бы
    сослаться на блок, который сами только что создали.

    written (Ф12, дефект 2) — диапазоны текста, которые внутри ЭТОГО вызова
    уже записала более ранняя операция батча; replace_text/replace_all,
    чей матч пересёкся с ними, отклоняются тем же путём, что и любая другая
    невалидная операция, — до того, как patch.apply вообще увидит op.

    ПАРТИЯ 1: невалидная операция, прежде чем стать ошибкой-с-ретраем,
    проверяется на избыточность ОТНОСИТЕЛЬНО этого же батча (_redundant_in_batch)
    — old==new или цель уже переписана более ранней операцией этого вызова.
    Такая операция молча пропускается (запись в applied честно называет её
    пропущенной), ретрай не тратится, батч не падает из-за собственного же
    прогресса (ColBERT 7, Математика 14)."""
    # written приходит снаружи и общий на всю правку (ПАРТИЯ 2, замер w10):
    # ColBERT 4 — первый кластер починил три числа через replace_text, второй
    # предложил replace_all на те же три, их в документе уже нет → жёсткая
    # ошибка и откат всей правки. Внутри одного вызова это ловит
    # _redundant_in_batch, но между кластерами written обнулялся.
    applied, retried, i = [], False, 0
    if written is None:
        written = {}
    anchor_chain = {}  # Н67: последний вставленный insert_after на каждый исходный якорь этого батча
    while i < len(ops):
        op = ops[i]
        # Н67: два insert_after с ОДНИМ якорем этого же батча дают обратный
        # порядок — оба целятся "после p16", второй ложится вплотную к якорю
        # и вытесняет первый вниз (модель добросовестно назвала верный якорь,
        # это механика addnext, а не суждение модели). Второй и последующие
        # insert_after на ТОТ ЖЕ исходный якорь перенаправляются на абзац,
        # вставленный ПРЕДЫДУЩИМ insert_after этого якоря — тогда порядок
        # вставок совпадает с порядком операций в ответе модели.
        anchor_id = op.get("id") if op.get("op") == "insert_after" else None
        if anchor_id is not None and anchor_id in anchor_chain:
            op = {**op, "id": anchor_chain[anchor_id]}
            ops[i] = op
        out = _out_of_lane(op, fragment_ids) if fragment_ids is not None else None
        term_err = _off_term_error(op, term_variants) if out is None else None
        if out is not None:
            targets, collision, err = [], None, f"блок {out!r} вне фрагмента, показанного в этом вызове — правь только то, что было показано"
        elif term_err is not None:
            targets, collision, err = [], None, term_err
        else:
            # Change (Ф16, item 4): targets/collision требуют полей вроде "old",
            # которые validate и создан проверять — считаем их только когда op
            # уже прошла validate, иначе _op_targets падает TypeError на op,
            # которую validate всё равно отклонил бы (например old=None).
            err = patch.validate(doc_map(doc, idx), op, doc)
            targets = _op_targets(doc, idx, op) if err is None else []
            # set_text не ИЩЕТ текст, а переписывает блок целиком: его цель —
            # весь абзац, поэтому она пересекается с любой более ранней записью
            # этого же батча в тот же блок, и гвард отказывал ей всегда (m11
            # замера w19: replace_text + set_text на p12 → правка, бывшая done
            # в w18, стала failed, а текст ошибки печатал «текст «None»» —
            # old у set_text нет). Редактировать собственный вывод она не
            # может по построению: старый текст блока целиком выбрасывается,
            # итог задаёт сама операция. Обратный порядок (set_text, потом
            # replace_text по написанному) гвардом по-прежнему ловится.
            collision = (_collision_source(targets, written)
                         if err is None and op.get("op") != "set_text" else None)
            if collision is not None:
                err = _own_output_error(op, collision)
        if err is None:
            before_ids = set(idx)
            applied.append(patch.apply(doc, idx, op))
            new_ids = set(idx) - before_ids
            if anchor_id is not None and new_ids:
                anchor_chain[anchor_id] = next(iter(new_ids))
            if ops_out is not None:
                ops_out.append(op)
            if fragment_ids is not None:
                fragment_ids |= new_ids
            if targets:
                _record_batch_write(op, targets, written)
            i += 1
            continue
        # пропуск — только для отказов ВАЛИДАТОРА. Операция вне полосы (out)
        # нарушает другую границу: кластер правит блок, которого ему не
        # показывали. Общий на всю правку written сделал такие операции
        # «избыточными» и глушил гвард полосы — поймано демо
        # test_invalid_cluster_aborts_whole_edit. Операция вне вариантов
        # термина (term_err, Н69) — та же логика: это отказ по ГРАНИЦЕ
        # применимости правки, не по совпадению с уже написанным этим же
        # батчем, молчаливый пропуск здесь замаскировал бы порчу чужой фразы.
        if out is None and term_err is None and _redundant_in_batch(op, idx, written):
            applied.append(f'пропущена операция {op.get("op")} (old={op.get("old")!r}) — избыточна относительно более ранней операции этого же батча: {err}')
            i += 1
            continue
        if retried or editor is None:
            return applied, err, 2 if retried else 1
        retried = True
        if fragment_ids is not None:
            # Находка Ф13-бис (ColBERT 19): предыдущие операции ЭТОГО ЖЕ батча уже
            # могли удалить/переместить блоки — ретрай обязан увидеть ТЕКУЩЕЕ
            # состояние документа, а не снимок, снятый до начала батча, иначе
            # Редактор предлагает удалить уже удалённое и валидатор бьёт "блок не найден".
            frag = find.fragment(doc_map(doc, idx), fragment_ids, around=1)
            fragment_text = render(frag)
            # Ф16, item 2: around=1 расширяет перерисованный фрагмент за пределы
            # fragment_ids (уже содержащего исходных соседей) — без этого блок,
            # реально показанный на ретрае, отклоняется гвардом как "вне
            # фрагмента", хотя он только что был на экране у Редактора.
            fragment_ids |= {b["id"] for b in frag}
        feedback = f'Операция {op} не прошла проверку: {err}. Пришли исправленный {{"ops": [...]}}.'
        reply = editor(fragment_text, request, feedback=feedback) or {}
        ops = _clean_ops(reply.get("ops"))
        if not ops:
            return applied, reply.get("note") or err, 2
        i = 0
    return applied, None, 2 if retried else 1


def _failed(reason, nav=None, editor_reply=None, tries=1, applied=None):
    """reply/iter обязаны быть в каждой записи, включая честные отказы —
    именно они интереснее всего в журнале для разбора «куда целился Навигатор».

    applied (Ф13-бис): операции, реально применённые к документу ДО сбоя,
    даже если документ откатан снимком, — раньше поле жёстко писалось [],
    и след (например три реальных delete перед упавшим insert_after) исчезал
    из журнала, хотя откат документа при этом был верным."""
    return {
        "verdict": "failed", "reason": reason, "applied": applied or [], "ids": [],
        "iter": tries, "reply": {"nav": nav, "editor": editor_reply},
    }


def _already(reason, nav, editor_reply=None, tries=1):
    """Находка Ф8 (item A) + Change C: rule-путь, ничего не изменивший
    (normalize дал пустой diff), — это НЕ провал сам по себе, но и не сразу
    "already": rule умеет отличить только "нормализация ничего не нашла" от
    "нормализация нашла и применила", а не "уже чисто" от "я не умею то, что
    попросили" (Математика edit 1 — двойной пробел и висящий пробел остались
    в документе, а rule смолчал, потому что искал не тот класс дефектов).
    Поэтому пустой diff у rule теперь restart'ит цикл обычным локальным путём
    (см. run_edit/_run_local), и already легитимен только если ЭТОТ путь тоже
    не нашёл, что менять (fallthrough=True в _run_local) — тогда rule и
    Редактор согласны, что менять нечего, и "failed" вводил бы в заблуждение
    не меньше ложного "done" (инвариант 5)."""
    return {
        "verdict": "already", "reason": reason, "applied": [], "ids": [],
        "iter": tries, "reply": {"nav": nav, "editor": editor_reply},
    }


def _restore_in_place(doc, idx, snapshot_path):
    """Восстанавливает doc/idx НА МЕСТЕ (мутирует переданные объекты, а не
    создаёт новую пару) и удаляет снимок. Нужна там, откуда нельзя вернуть
    вызывающему новую пару (result, doc, idx) обычным return — управление
    уходит через исключение (item D). Вызывающий держит СТАРУЮ ссылку на doc,
    и после падения Проверяющего она обязана снова стать нетронутой, а не
    домашним объектом с половиной правки внутри."""
    fresh = Document(snapshot_path)
    body = doc.element.body
    for child in list(body):
        body.remove(child)
    for child in list(fresh.element.body):
        body.append(child)
    idx.clear()
    idx.update(index(doc))
    os.remove(snapshot_path)


def _hf_state(doc):
    """(header_linked, footer_linked) последнего раздела — снимок ДО
    применения операций сравнивается с ЭТИМ ЖЕ вызовом ПОСЛЕ (В2-бис): смена
    False означает, что set_header_footer завёл отдельную часть пакета."""
    sec = doc.sections[-1]
    return (sec.header.is_linked_to_previous, sec.footer.is_linked_to_previous)


def _move_no_op_error(applied_ops, before, after):
    """В11 (находка Н68): «перенеси пункт про окно на первое место» дала два
    move_after, которые в сумме вернули список в исходный порядок — оба
    применились без ошибки (patch.apply не бросает исключение просто потому,
    что итог оказался бессмысленным), и вердикт был done. Код обязан судить
    по ИТОГОВОМУ порядку конкретно ПЕРЕМЕЩАЕМЫХ id, а не по факту применения
    операции: если КАЖДЫЙ id, который двигала хотя бы одна move_after этого
    батча, оказался на ТОЙ ЖЕ позиции, что и до правки, — перенос отменил сам
    себя, реально ничего не переместилось. Позиция сравнивается по индексу в
    полном списке блоков (move_after не меняет состав id, только порядок).
    None — хотя бы один из перемещаемых id реально сменил позицию (обычный
    случай), проверять больше нечего."""
    moved_ids = {op["id"] for op in applied_ops if op.get("op") == "move_after"}
    if not moved_ids:
        return None
    pos_before = {b["id"]: i for i, b in enumerate(before)}
    pos_after = {b["id"]: i for i, b in enumerate(after)}
    if any(pos_before.get(i) != pos_after.get(i) for i in moved_ids):
        return None
    return ("правка перемещает " + ", ".join(sorted(moved_ids)) + ", но итоговая позиция "
            + ("этого блока" if len(moved_ids) == 1 else "этих блоков")
            + " в документе совпадает с исходной — перенос отменил сам себя, "
              "фактически ничего не переместилось")


def _finish(doc, idx, snapshot_path, blocks_before, applied, request, checker, nav, editor_reply, tries,
            hf_before=None, applied_ops=()):
    """Общий хвост ПОСЛЕ применения операций — общий и для одного вызова
    Редактора, и для нескольких (см. _run_clusters): diff по всему снимку →
    Проверяющий → вердикт → коммит/откат. Ровно один снимок, один diff, один
    вызов Проверяющего на всю правку — граница транзакции не дробится вместе
    с шагами (см. спецификацию задачи про кластеризацию). Возвращает
    (result, doc, idx, tries); result is None ТОЛЬКО когда diff пуст И
    колонтитул не менялся — смысл пустого diff разный на разных путях
    (item A/C), решение оставлено вызывающему, а doc/idx в этом случае уже
    НОВАЯ пара из _restore.

    hf_before (В2-бис) — снимок _hf_state ДО применения, взятый вызывающим
    рядом с blocks_before. Колонтитул НЕ часть doc_map() (см. «Контракты» в
    BUILD_PLAN.md) — правка, менявшая только его, всегда даёт ПУСТОЙ
    текстовый diff тела документа, и без этого параметра честная правка
    неотличима от «ничего не изменилось» (item A).

    applied_ops (В11, находки Н66/Н68) — сырые op РЕАЛЬНО применённых операций
    (см. _apply_ops/ops_out), нужны _trace_error (проверять СДЕЛАННОЕ, а не
    верить ярлыку trace от Навигатора) и _move_no_op_error (перенос, отменивший
    сам себя, не должен считаться перемещением)."""
    blocks_after = doc_map(doc, idx)
    diff = _diff(blocks_before, blocks_after)
    hf_changed = hf_before is not None and hf_before != _hf_state(doc)
    if not diff and not hf_changed:
        doc, idx = _restore(snapshot_path)
        return None, doc, idx, tries

    # В1: класс изменения проверяется КОДОМ по РЕАЛЬНО применённым операциям
    # раньше, чем тратится вызов Проверяющего — он видит только текстовый
    # diff и не отличит строку таблицы, ставшую абзацем, от настоящей строки
    # (см. _trace_error).
    trace_err = _trace_error(nav.get("trace"), blocks_before, blocks_after, doc, applied_ops)
    if trace_err is not None:
        doc, idx = _restore(snapshot_path)
        reply = {"nav": nav, "editor": editor_reply}
        return ({"verdict": "failed", "reason": trace_err, "applied": applied, "ids": [],
                  "iter": tries, "reply": reply}, doc, idx, tries)

    # Н68: move_after, применившийся без ошибки, ещё не значит «переместил» —
    # судим по итоговой позиции конкретно перемещаемых id, не по факту apply.
    move_err = _move_no_op_error(applied_ops, blocks_before, blocks_after)
    if move_err is not None:
        doc, idx = _restore(snapshot_path)
        reply = {"nav": nav, "editor": editor_reply}
        return ({"verdict": "failed", "reason": move_err, "applied": applied, "ids": [],
                  "iter": tries, "reply": reply}, doc, idx, tries)

    if not diff:
        # Колонтитул изменился, тело — нет: Проверяющему буквально нечего
        # сравнивать (diff пуст по построению, не по ошибке), а trace_err
        # выше уже структурно подтвердил, что часть пакета и ссылка в
        # w:sectPr появились. Дальше звать LLM было бы вызовом ради вызова
        # (инвариант 1) — вердикт решает код.
        os.remove(snapshot_path)
        reason = "колонтитул изменён — подтверждено структурно (часть пакета + ссылка в w:sectPr), текстового diff тела документа для этой правки нет"
        return ({"verdict": "done", "reason": reason, "applied": applied, "ids": [],
                  "iter": tries, "reply": {"nav": nav, "editor": editor_reply}}, doc, idx, tries)

    try:
        verdict = checker(request, diff) or {}
    except Exception:
        # item D: транспорт (или что угодно другое) умер во время вызова Проверяющего —
        # патч уже применён к живому doc, снимок ещё жив. Молчать нельзя (инвариант 6),
        # но и оставлять doc мутированным-непроверенным нельзя (инвариант 5): восстанавливаем
        # ЭТИ ЖЕ объекты doc/idx на месте (см. _restore_in_place — обычный _restore тут не
        # годится, он возвращает НОВУЮ пару, а мы не можем сделать return из except) и
        # поднимаем исходное исключение дальше — громко, как и было.
        _restore_in_place(doc, idx, snapshot_path)
        raise

    ids_touched = [d["id"] for d in diff]
    reply = {"nav": nav, "editor": editor_reply}
    if verdict.get("ok"):
        os.remove(snapshot_path)
        return {"verdict": "done", "reason": verdict.get("reason", ""), "applied": applied, "ids": ids_touched,
                 "iter": tries, "reply": reply}, doc, idx, tries

    doc, idx = _restore(snapshot_path)
    return {"verdict": "rolled_back", "reason": verdict.get("reason", ""), "applied": applied, "ids": ids_touched,
             "iter": tries, "reply": reply}, doc, idx, tries


def _apply_and_check(doc, idx, ops, fragment_text, request, use_editor, nav, editor_reply, checker):
    """Путь одного вызова Редактора (только rule — normalize мимо кластеров,
    см. run_edit): снимок → применение операций → _finish. См. _finish за
    диффом/Проверяющим/вердиктом и _run_clusters за путём с кластерами
    (единственным путём для локальных правок через Редактора)."""
    snapshot_path = _snapshot(doc)
    blocks_before = doc_map(doc, idx)
    ops_applied = []
    applied, err, tries = _apply_ops(doc, idx, ops, fragment_text, request, use_editor, ops_out=ops_applied)

    if not applied:
        doc, idx = _restore(snapshot_path)
        return _failed(err or "ни одна операция не применилась", nav, editor_reply, tries, applied), doc, idx, tries

    return _finish(doc, idx, snapshot_path, blocks_before, applied, request, checker, nav, editor_reply, tries,
                    applied_ops=ops_applied)


def _cluster(blocks, ids, around=1):
    """Группирует resolved id по соседству в порядке документа: окно цели —
    она сама плюс around соседей с каждой стороны (та же идея, что и у
    find.fragment). Окна, которые пересекаются, сливаются в один кластер —
    два id в соседних абзацах остаются ОДНИМ шагом, а разбросанные по
    документу id расходятся по разным. Кластеры и id внутри них — в порядке
    документа. Позиции берутся из blocks на момент вызова (до начала цикла
    правок в _run_clusters) — порядок кластеров этим и фиксируется, дальше
    внутри цикла меняется только содержимое фрагмента, не разбиение."""
    pos = {b["id"]: i for i, b in enumerate(blocks)}
    ordered = sorted(ids, key=lambda i: pos[i])
    clusters, cur, cur_end = [], [], None
    for i in ordered:
        p = pos[i]
        if cur_end is not None and p - around <= cur_end:
            cur.append(i)
            cur_end = max(cur_end, p + around)
        else:
            if cur:
                clusters.append(cur)
            cur, cur_end = [i], p + around
    if cur:
        clusters.append(cur)
    return clusters


_FRAGMENT_CHAR_LIMIT = 15000  # Ф20: см. гвард объёма в _run_clusters, ниже


def _run_clusters(doc, idx, blocks, ids, request, editor, checker, nav, fallthrough, single_cluster=False):
    """Путь с несколькими маленькими шагами вместо одного большого фрагмента
    (измерено на 40 живых правках: Редактор отказывает по ОБЪЁМУ, а не по
    смыслу, когда целей много — edit с 4 целей до 10 упала done→rolled_back).
    Резолвленные id группируются в кластеры (_cluster), и каждый кластер
    получает СВОЙ вызов Редактора на СВЕЖЕМ doc_map (обязательно — предыдущие
    кластеры уже мутировали документ, старая карта дала бы Редактору "old",
    которого больше нет, и validate его отклонит).

    single_cluster=True (Ф20, kind="compose") — правка строит одно целое из
    нескольких мест документа, и кластеризация по соседству здесь как раз
    вредна: она специально держит цели раздельными. `around` для _cluster
    ниже раздувается до размера документа — тогда условие слияния окон
    (`p - around <= cur_end`) истинно для любой пары id, и _cluster
    гарантированно возвращает ОДИН кластер из ВСЕХ резолвленных id, в
    порядке документа. Дальше код тот же самый: один элемент в clusters даёт
    один вызов Редактора на фрагмент из всех целей плюс их соседи (те же
    ±1, что и всегда — see find.fragment ниже), транзакция и Проверяющий не
    меняются — они и так уже одни на всю правку, а не на кластер.

    Транзакция и Проверяющий — по-прежнему ОДНИ на правку целиком (_finish):
    шаги дробятся, обязательство — нет. Кластер, где Редактор честно вернул
    пустые ops, — пропускается, не проваливает правку (другим кластерам ещё
    есть что делать); кластер, чьи ops не прошли валидацию даже после ретрая
    внутри _apply_ops, — прерывает ВЕСЬ цикл, откатывая единственный снимок.

    Change 1 (Ф13): инвентарь вариантов написания (_variant_inventory)
    считается ОДИН раз по исходным blocks, до цикла, и кладётся в начало
    fragment_text КАЖДОГО кластера — иначе Редактор кластера видит только
    тот вариант, что уже стоит в его фрагменте, и "унифицирует" правку к
    нему же (ColBERT 7/15, old==new).

    Change 3 (Ф13): набор clusters зафиксирован ВЫШЕ, до первой мутации.
    done требует, чтобы КАЖДЫЙ кластер этого набора либо дал diff, либо
    честно вернул пустые ops (skip) — иначе набор целей обработан не
    полностью, даже если другие кластеры реально что-то поменяли и
    Проверяющий был бы не против. Кластер, чьи ops применились БЕЗ ошибки,
    но не дали diff (partial), — не failed (часть правки реально сработала)
    и не already (документ был не таким же — что-то изменилось), поэтому
    verdict переиспользует rolled_back: смысл тот же, что при отказе
    Проверяющего — "применили, но в силу не вступило", документ
    восстанавливается. Проверяющего в этом случае не зовём — вопрос
    решает код, а не мнение модели (см. BUILD_PLAN Ф13, "не строить ковёр
    покрытия требований" — здесь считаются только кластеры, не пункты
    запроса)."""
    snapshot_path = _snapshot(doc)
    blocks_before = doc_map(doc, idx)
    hf_before = _hf_state(doc)
    clusters = _cluster(blocks, ids, around=len(blocks) if single_cluster else 1)
    inventory = _variant_inventory(blocks, nav, request)
    # Н69: та же правка класса «единое написание термина», но упавшая на
    # ЛОКАЛЬНЫЙ путь (см. _run_unify → _run_local при _inflects/без единого
    # канона) — инвентарь уже посчитан для промпта (см. inventory выше),
    # берём его же набором вариантов для _off_term_error, второй инвентарь не
    # строим. Только когда Навигатор НАЗВАЛ класс unify (nav["kind"]) — иначе
    # это обычная local-правка, у которой инвентарь варьируется по ДРУГОЙ
    # причине (несколько цитат старого/нового текста, см. edit_demo.py
    # test_edit_12_on_real_doc_fixture) и не означает «трогать только термин».
    term_variants = ({v for v, n in _variant_counts(blocks, nav, request)}
                      if inventory and nav.get("kind") == "unify" else None)

    applied_all, editor_replies, tries_total, partial, replace_all_seen = [], [], 0, False, set()
    ops_all = []  # В11: сырые op успешно применённых операций, см. _apply_ops/ops_out и _trace_error
    written = {}  # общий на все кластеры правки, см. _apply_ops
    try:
        for cluster_ids in clusters:
            pre_cluster = doc_map(doc, idx)
            frag_blocks = find.fragment(pre_cluster, cluster_ids, around=1)
            if not frag_blocks:
                # Ф16, item 3: цели этого кластера уже пропали (удалены/слиты более
                # ранним кластером) — пустой фрагмент даёт ПУСТОЕ множество
                # fragment_ids, гвард полосы активен и отклонит любой ответ
                # Редактора; тупик, ретрай не спасает. Пропускаем кластер честно.
                continue
            fragment_text = render(frag_blocks)
            # ПАРТИЯ 5: кластеры слепы друг к другу, а текст правки каждый получает
            # ЦЕЛИКОМ — отсюда двойная работа и откат чужой. Замерено: ColBERT 14
            # расшифровала MRR@10 дважды в двух кластерах (Проверяющий завернул
            # всю правку), ColBERT 4 — третий кластер предложил вернуть точку
            # вместо запятой в числе, которое первый уже исправил. Форма та же,
            # что у инвентаря вариантов: посчитанная кодом строка в начало
            # фрагмента, лишнего вызова модели не нужно.
            if applied_all:
                done_note = "Уже сделано в этой правке (не повторяй и не отменяй):\n" + "\n".join(
                    f"- {a}" for a in applied_all)
                fragment_text = f"{done_note}\n\n{fragment_text}"
            if inventory:
                fragment_text = f"{inventory}\n\n{fragment_text}"
            if len(fragment_text) > _FRAGMENT_CHAR_LIMIT:
                # Ф20: гвард объёма. compose собирает фрагмент из ВСЕХ резолвленных
                # целей сразу (single_cluster выше) — именно здесь фрагмент способен
                # вырасти настолько, что уйдёт за окно модели. Честный отказ вместо
                # переполнения контекста (ContextWindowExceededError уже случался,
                # см. Ф13-бис) — код заранее знает размер строки, которую собирается
                # отправить, доказывать это вызовом не нужно.
                doc, idx = _restore(snapshot_path)
                reason = (f"фрагмент для этой правки слишком большой: {len(fragment_text)} знаков "
                          f"(порог {_FRAGMENT_CHAR_LIMIT}) — не поместится в контекст модели, правка отклонена")
                return _failed(reason, nav, editor_replies, tries_total, applied_all), doc, idx
            fragment_ids = {b["id"] for b in frag_blocks}
            reply = editor(fragment_text, request) or {}
            editor_replies.append(reply)
            tries_total += 1
            ops = _clean_ops(reply.get("ops"))
            # Ф16, item 1: replace_all документ-широкая, и каждый кластер видит
            # ПОЛНЫЙ текст правки — один и тот же replace_all может прийти от
            # нескольких кластеров подряд (written внутри _apply_ops этого не
            # ловит, он заводится заново на каждый вызов). Повтор молча не меняет
            # текст, diff кластера пуст → partial → откатывает уже верную работу
            # более раннего кластера. Дедуплицируем по (old, new) между кластерами.
            ops = [o for o in ops if o.get("op") != "replace_all" or (o.get("old"), o.get("new")) not in replace_all_seen]
            replace_all_seen |= {(o.get("old"), o.get("new")) for o in ops if o.get("op") == "replace_all"}
            if not ops:
                continue
            applied, err, cluster_tries = _apply_ops(doc, idx, ops, fragment_text, request, editor, fragment_ids, written,
                                                      ops_out=ops_all, term_variants=term_variants)
            tries_total += cluster_tries - 1  # первый вызов кластера уже посчитан выше, тут доучитывается только ретрай
            applied_all += applied
            if err is not None:
                doc, idx = _restore(snapshot_path)
                return _failed(err, nav, editor_replies, tries_total, applied_all), doc, idx
            if not _diff(pre_cluster, doc_map(doc, idx)):
                partial = True  # ops применились без ошибки, но эта цель по факту не обработана
    except Exception:
        # В11 (находка): editor() зовётся ПОСЛЕ того, как более ранние кластеры
        # этого же батча уже мутировали doc через patch.apply. Раньше исключение
        # из этого вызова (например обрыв транспорта) улетало наружу СРАЗУ, минуя
        # весь код восстановления ниже (он написан как return-путь, а не
        # try/except) — doc оставался мутированным напополовину, а вызывающий
        # (bench/run_seq.py, run.py, server.py) при ретрае той же правки на тех
        # же doc/idx получал уже испорченный документ и не знал об этом (замер
        # w18: colbert#4 и math#4 — верные по кластеру правки survived в файле
        # под вердиктом failed/rolled_back). Восстанавливаем ТЕ ЖЕ doc/idx на
        # месте (см. _restore_in_place — обычный _restore тут не годится, мы не
        # можем сделать return из except) и поднимаем исходное исключение дальше.
        _restore_in_place(doc, idx, snapshot_path)
        raise

    if not applied_all:
        doc, idx = _restore(snapshot_path)
        if fallthrough:
            reason = "нормализация ничего не нашла, и Редактор ни в одном кластере не предложил операций — оба пути согласны, что менять нечего"
            return _already(reason, nav, editor_replies, tries_total), doc, idx
        # ПАРТИЯ 4: Редактор умеет сказать «здесь уже всё так» (already=true),
        # и это правильный исход, а не отказ — ColBERT 15 просит переставить
        # уровни списка, которые в документе УЖЕ расставлены верно (проверено
        # по файлу: p51/54/57 — ilvl 0, остальные ilvl 1). Раньше вердикт
        # «уже так» жил только на пути rule, и верный ответ модели
        # записывался как failed. Условие двойное: так сказал КАЖДЫЙ кластер
        # И код подтвердил, что изменений нет (applied_all пуст) — по одному
        # заявлению модели already не выдаётся (инвариант 5).
        if editor_replies and all(r.get("already") is True for r in editor_replies):
            reason = "Редактор во всех кластерах сообщил, что менять нечего — документ уже в требуемом виде"
            return _already(reason, nav, editor_replies, tries_total), doc, idx
        return _failed("редактор не предложил операций ни в одном из кластеров", nav, editor_replies, tries_total, applied_all), doc, idx

    diff_all = _diff(blocks_before, doc_map(doc, idx))
    if partial and diff_all:
        doc, idx = _restore(snapshot_path)
        reason = "часть кластеров правки не дала изменений, хотя Редактор предлагал для них операции — цель обработана не полностью"
        return {"verdict": "rolled_back", "reason": reason, "applied": applied_all,
                "ids": [d["id"] for d in diff_all], "iter": tries_total,
                "reply": {"nav": nav, "editor": editor_replies}}, doc, idx

    result, doc, idx, tries = _finish(doc, idx, snapshot_path, blocks_before, applied_all, request, checker, nav,
                                       editor_replies, tries_total, hf_before, ops_all)
    if result is not None:
        return result, doc, idx
    return _failed("операции применились, но текст не изменился", nav, editor_replies, tries), doc, idx


def _word_pattern(text):
    """Regex словограничного, пробельно-гибкого поиска text по всему
    документу — та же техника, что и find._flex_span (части, разбитые по
    пробельным разрывам, между ними \\s+), плюс границы слова (?<!\\w)…(?!\\w)
    снаружи, чтобы «Bi-encoder» не считался найденным внутри «Bi-encoders»."""
    parts = [re.escape(p) for p in re.split(r"\s+", text) if p]
    return r"(?<!\w)" + r"\s+".join(parts) + r"(?!\w)"


_CYRILLIC_RX = re.compile(r"[а-яё]", re.IGNORECASE)


def _inflects(word):
    """В6: True — word похоже на русскую словоформу, которая может менять
    окончание по падежу/числу/роду. unify заменяет буквально, без спряжения
    (replace_all по всему документу) — измерено дважды на battery: канон
    «литий-ионный» (именительный, ед.ч., муж.р.) встал во ВСЕ позиции,
    включая те, где нужен был другой падеж/число («литий-ионный
    аккумуляторы», «литий-ионный состоит»). Такое умеет только Редактор
    (локальный путь, per-occurrence).

    Латиница, аббревиатуры (ВСЕ буквы прописные — не склоняются как обычное
    слово), числа и даты — безопасны для буквальной замены, поэтому не
    кириллица или кириллица целиком в верхнем регистре не считается
    инфлексией."""
    return bool(_CYRILLIC_RX.search(word)) and word != word.upper()


def _run_unify(doc, idx, blocks, nav, request, editor, checker, unifier):
    """Ф18: правки вида «сделай одинаково по всему документу» (унификация
    термина, дат, чисел) — по замеру w12 самый большой источник провалов и
    единственный источник лжи (ColBERT 7: вердикт done при ЧЕТЫРЁХ написаниях
    Bi-encoder в файле). Причина — кластеры (_run_clusters) видят только свой
    кусок документа и "унифицируют" к тому варианту, который уже стоит перед
    ними. Здесь ОДИН вызов модели решает, какие пары заменить, а всю мутацию
    и весь вердикт делает код (инвариант 1/5) — Проверяющий-LLM на этом пути
    не зовётся вовсе, вердикт — это счёт оставшихся вхождений.

    Инвентарь (_variant_counts) пуст, если в документе меньше двух реально
    найденных вариантов — Навигатор промахнулся с маршрутом unify, это
    обычная локальная (или пустая) правка: тот же путь, что и раньше до Ф18.

    Дефект w13 (ColBERT 7): вердикт "done" сверялся только с ПАРАМИ, которые
    назвала модель — вариант, который она не назвала (или обрубок вроде
    "Single-vector" вместо "Single-Vector Bi-encoders"), молча оставался в
    документе, а код всё равно говорил "заменено". Теперь: (1) применяется
    только пара, чей old буквально совпадает с посчитанным инвентарём — код
    посчитал документ, модель нет, невыдуманный вариант не портит текст;
    (2) все применённые пары обязаны сходиться к ОДНОМУ new — иначе модель
    не выбрала канон, это честный failed; (3) вердикт проверяется по ВСЕМУ
    инвентарю, а не по списку пар модели — вариант, не попавший ни в одну
    применённую пару, тоже обязан пропасть из документа."""
    counts = _variant_counts(blocks, nav, request)
    if len(counts) < 2:
        return _run_local(doc, idx, blocks, nav, request, editor, checker)
    inventory = _variant_inventory(blocks, nav, request)

    reply = unifier(inventory, request) or {}
    pairs = [tuple(p) for p in (reply.get("pairs") or []) if isinstance(p, (list, tuple)) and len(p) == 2]
    if not pairs:
        return _failed(reply.get("note") or "модель не предложила ни одной пары для унификации", nav, reply), doc, idx

    # Замер w14: маршрут не должен ПЕРЕХВАТЫВАТЬ правку, которую он не тянет.
    # Пары не совпали с инвентарём (Математика 5) или разошлись по нескольким
    # канонам (ColBERT 4 — шесть разных чисел, ColBERT 12 — две формулировки):
    # это не унификация одного написания, а обычная локальная правка, и в w12
    # локальный путь её делал. Отказ здесь был чистой потерей: −4 правки.
    variant_set = {v for v, n in counts}
    pairs = [(old, new) for old, new in pairs if old != new and old in variant_set]

    # В6: русская словоформа, способная склоняться, не унифицируется буквальной
    # заменой (см. _inflects) — это работа Редактора, не document-wide replace_all.
    if any(_inflects(old) or _inflects(new) for old, new in pairs):
        return _run_local(doc, idx, blocks, nav, request, editor, checker)

    canonicals = {new for old, new in pairs}
    if len(canonicals) != 1:
        return _run_local(doc, idx, blocks, nav, request, editor, checker)
    canonical = canonicals.pop()

    # УБЫВАНИЕ длины old — иначе «Bi-encoder» переписал бы внутренность
    # «Bi-encoders» до того, как до неё дойдёт её собственная пара.
    pairs = sorted(pairs, key=lambda p: -len(p[0]))
    snapshot_path = _snapshot(doc)
    applied, replaced_n = [], 0
    for old, new in pairs:
        op = {"op": "replace_all", "old": old, "new": new, "word": True}
        err = patch.validate(doc_map(doc, idx), op, doc)
        if err is not None:
            continue
        desc = patch.apply(doc, idx, op)
        applied.append(desc)
        m = re.search(r"Заменено (\d+) вхождений", desc)
        replaced_n += int(m.group(1)) if m else 0

    # Вердикт по СВОЕМУ инвентарю (Defect 1), не по списку пар модели.
    # Вариант, оказавшийся ПОДСТРОКОЙ канонической формы (Defect 2, Математика
    # 5: канон добавил кавычки вокруг старого текста), не считается
    # оставшимся — он неизбежно найдётся внутри canonical.
    blocks_after = doc_map(doc, idx)
    remaining = [v for v, n in counts if v != canonical and v not in canonical
                 and find.by_regex(blocks_after, _word_pattern(v))]
    if remaining:
        doc, idx = _restore(snapshot_path)
        reason = "не удалось привести к одному написанию, остались варианты: " + ", ".join(f"«{r}»" for r in remaining)
        return _failed(reason, nav, reply, applied=applied), doc, idx

    diff_all = _diff(blocks, blocks_after)
    if not diff_all:
        os.remove(snapshot_path)
        return _already("документ уже унифицирован — заменять было нечего", nav, reply), doc, idx

    os.remove(snapshot_path)
    reason = f"заменено {replaced_n} вхождений {len(applied)} вариантов"
    return {"verdict": "done", "reason": reason, "applied": applied, "ids": [d["id"] for d in diff_all],
            "iter": 1, "reply": {"nav": nav, "editor": reply}}, doc, idx


def _run_local(doc, idx, blocks, nav, request, editor, checker, fallthrough=False, single_cluster=False):
    """Локальный путь через Редактора: резолв id → кластеризация → цикл
    маленьких шагов (_run_clusters, один вызов Редактора на кластер). Нет
    верхней границы на число целей и нет отдельной ветки для одной цели —
    один резолвленный id это тоже кластер, просто единственный, а
    единообразный цикл короче, чем branch на N==1 (владелец: обязательство
    транзакции не меняется от того, сколько шагов внутри). Используется и
    как обычный (non-rule) путь run_edit, и как fallthrough item C — когда
    rule ничего не изменил и цикл перезапускает ТОТ ЖЕ запрос обычным путём.
    fallthrough=True меняет только то, каким вердиктом закрывается "здесь
    нечего резолвить/Редактор честно отказался": already (rule и Редактор
    согласны — менять нечего), а не failed.

    single_cluster (Ф20) прокидывается в _run_clusters как есть — resolve и
    честный отказ "негде править" не меняются вовсе, разница только в форме
    кластеризации резолвленных id (см. run_edit, kind="compose")."""
    ids = _resolve(blocks, nav, request)
    if not ids:
        if fallthrough:
            verdict_fn = _already
            reason = "нормализация ничего не нашла, а обычный поиск (id/якоря/цитаты) тоже не нашёл, где это применить — похоже, менять действительно нечего"
        else:
            verdict_fn = _failed
            reason = "не нашёл, где это править: ни id и якоря Навигатора, ни дословные цитаты из текста правки не нашли места в документе"
        return verdict_fn(reason, nav), doc, idx

    return _run_clusters(doc, idx, blocks, ids, request, editor, checker, nav, fallthrough, single_cluster)


def run_edit(doc, idx, request, navigator=_navigate, editor=_edit_llm, checker=_check, unifier=_unify_llm):
    """Один цикл правки. Возвращает (result, doc, idx) — после отката
    (verdict != "done" после применения) doc/idx уже перечитаны из снимка,
    старые ссылки вызывающего использовать нельзя.

    result содержит "reply": {"nav": ..., "editor": ...} — РАЗОБРАННЫЙ JSON-
    ответ ролей (llm.chat парсит его сам, сырое тело HTTP нигде не хранится).
    "editor": None, когда Редактора не звали вообще (путь rule и он ничего не
    нашёл менять); на локальном пути (_run_local/_run_clusters) "editor" —
    СПИСОК ответов, по одному на кластер (даже если резолвился один id и
    кластер тоже один) — иначе список из N ответов выглядел бы как один
    вызов, а их было N. "iter" — настоящее число обращений к Редактору за
    всю правку: по одному на кластер плюс по одному за каждый ретрай внутри
    _apply_ops (на пути rule, где Редактора не звали, — 1, как и раньше), не
    декоративная константа.

    Change C, расширено дефектом w13: пустой diff у rule ИЛИ rolled_back
    (Проверяющий отклонил нормализацию — rule ухватил не тот класс дефекта,
    Математика 2/6) — не терминал. Код продолжает ТЕМ ЖЕ запросом обычным
    локальным путём (_run_local с fallthrough=True) — rule не умеет отличить
    "уже чисто"/"не тот класс" от "не умею это делать", это умеет только
    реальная попытка через Редактора. done у rule — по-прежнему терминал.

    Ф18: kind="unify" (навигатор) уходит в _run_unify — там "editor" в reply
    не список ответов по кластерам, а ОДИН ответ unifier (пары "старое"→
    "новое"), Проверяющий-LLM не зовётся вовсе, вердикт считает код.

    Замер w14 отменил обратный порядок: rule ВЫШЕ unify, как и было до Ф18.
    Когда Навигатор проставлял оба, а выигрывал unify, ломались ColBERT 6
    (кавычки) и Математика 1 (пробелы) — обе делались нормализацией и обе
    упали. Защита от неверного rule — не приоритет unify, а fallthrough
    ниже: откат Проверяющего продолжается локальным путём.

    Ф20: kind="compose" (Навигатор) идёт тем же _run_local/_run_clusters, что
    и обычная local-правка — единственная разница в single_cluster=True: одна
    правка строит одно целое из нескольких мест документа, поэтому
    кластеризация по соседству здесь противоречит задаче, а не помогает (см.
    _run_clusters). Своего "editor"/"reply" формата у compose нет — reply
    остаётся списком из ОДНОГО ответа (один кластер — один вызов)."""
    blocks = doc_map(doc, idx)
    nav = navigator(find.outline(blocks), request) or {}
    rule = nav.get("rule")

    if not rule:
        if nav.get("kind") == "unify":
            return _run_unify(doc, idx, blocks, nav, request, editor, checker, unifier)
        if nav.get("kind") == "compose":
            return _run_local(doc, idx, blocks, nav, request, editor, checker, single_cluster=True)
        return _run_local(doc, idx, blocks, nav, request, editor, checker)

    # Правки типа rule идут мимо Редактора — код нормализует сам, LLM не зовём.
    ops, fragment_text = [{"op": "normalize", "rule": rule}], ""
    result, doc, idx, _tries = _apply_and_check(doc, idx, ops, fragment_text, request, None, nav, None, checker)
    if result is not None and result.get("verdict") != "rolled_back":
        return result, doc, idx
    # doc/idx здесь уже НОВАЯ пара из _restore (см. _finish — и для пустого
    # diff, и для rolled_back восстановление уже случилось до возврата сюда)
    # — blocks обязан быть пересчитан на них, старый blocks использовать нельзя.
    # fallthrough (закрывать already вместо failed, если локальный путь тоже
    # ничего не нашёл) законен ТОЛЬКО для пустого diff: там rule и Редактор
    # согласны, что менять нечего. После rolled_back нормализация что-то
    # изменила, и Проверяющий это отклонил — "менять нечего" было бы неправдой.
    return _run_local(doc, idx, doc_map(doc, idx), nav, request, editor, checker, fallthrough=result is None)


_ITEM_MARKER = re.compile(r"^(?:\*\*(\d+)\.\*\*|(\d+)[.)]|[-*])\s+")


def split(request):
    """Делит многопунктный запрос на атомарные правки по markdown-нумерации
    (**1.**, 1., 1), -, * в начале строки). Заголовки (#, ##…) и пустые строки
    отбрасываются, текст пункта тянется до следующего маркера — многострочные
    пункты не рвутся. Без структуры — [request] без изменений. Перенесено из
    прошлого проекта (docx-agent/agent.py) — там уже проверено на этом же
    файле правок."""
    items, current = [], None
    for line in request.splitlines():
        stripped = line.strip()
        if not stripped or stripped.startswith("#"):
            continue
        m = _ITEM_MARKER.match(stripped)
        if m:
            if current is not None:
                items.append(current.strip())
            current = stripped[m.end():]
        elif current is not None:
            current += " " + stripped
    if current is not None:
        items.append(current.strip())
    return items if items else [request]
