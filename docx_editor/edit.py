_ID_PREFIX = re.compile(r"^p\d+\s+")


def _strip_anchor(anchor):
    """Защита от находки Ф5: модель иногда кладёт id прямо внутрь цитаты якоря."""
    return _ID_PREFIX.sub("", anchor)


_QUOTE_RX = re.compile(r"«([^»]+)»|`([^`]+)`|\"([^\"]+)\"|“([^”]+)”")


def _quotes(request):
    """Дословные цитаты из текста правки во всех употребимых кавычках —
    «ёлочках», `обратных`, "прямых" и “типографских” — короче 2 знаков не считаем."""
    out = []
    for m in _QUOTE_RX.finditer(request):
        q = next(g for g in m.groups() if g is not None)
        if len(q) >= 2:
            out.append(q)
    return out


_NUM_RX = re.compile(r"\d+[.,]\d+%?")


def _literals(request):
    """Дословные якоря из текста правки: цитаты в кавычках плюс числа с
    дробной частью.

    ПАРТИЯ 2. Числа приходится брать отдельно: их не заключают в кавычки, и
    ColBERT 4 («Проценты записаны через точку… 4.2%, 6.7%, 36.2%, 0.4448,
    0.4436, 8.8 млн») давала пустой поиск — Навигатор вернул ids: [] и
    anchors: [], цитат в правке нет, искать было нечем. При этом все шесть
    строк лежат в документе дословно (p67, p73, p77, p102). Дробная часть
    обязательна: она отсекает шум вроде «20 правок» и номеров разделов."""
    return _dedupe(_quotes(request) + _NUM_RX.findall(request))


_PATTERN_MAX_SHARE = 0.7  # В5: доля блоков документа (большинство и больше), выше которой совпадение регулярки неправдоподобно


def _pattern_ids(blocks, pattern):
    """id блоков, где найден pattern — регулярное выражение от Навигатора
    (В5): «даты приведи к формату ДД.ММ.ГГГГ» адресуется ФОРМАТОМ, а не
    дословной цитатой — цитаты для формата не существует, поиск по ней
    честно ничего не находил (тот же корень, что у ColBERT 4 с процентами,
    Ф16). find.by_regex уже умеет искать по регулярке — второй поиск не
    пишем, код только компилирует и защищает.

    Два гварда против модели-автора регулярки: невалидный regex — [], как
    будто адреса не было (а не исключение наружу); regex, нашедший
    неправдоподобную долю блоков документа (> _PATTERN_MAX_SHARE) — тоже []:
    жадная/сломанная регулярка иначе адресовала бы правку на ВЕСЬ документ
    вместо честного отказа."""
    try:
        rx = re.compile(pattern)
    except re.error:
        return []
    hits = find.by_regex(blocks, rx)
    if blocks and len(hits) / len(blocks) > _PATTERN_MAX_SHARE:
        return []
    return hits


def _clean_ops(ops):
    """Отбрасывает мусорные элементы списка ops — на 26B модель иногда кладёт
    посторонний примитив (например 0) первым элементом рядом с валидными
    операциями. Валидатор всё равно проверит каждую оставшуюся операцию по
    существу — здесь только защита от AttributeError на не-словаре."""
    return [op for op in (ops or []) if isinstance(op, dict)]


def _dedupe(ids):
    seen, out = set(), []
    for i in ids:
        if i not in seen:
            seen.add(i)
            out.append(i)
    return out


def _normalize_id(raw):
    """Приводит id от Навигатора к канонической форме блоков ("p12", "t3"):
    модель то возвращает голое число (112 вместо "p112"), то путает регистр
    префикса ("P112") — код, не промпт, отвечает за форму (находка Ф5, тот
    же класс, что и id внутри цитаты якоря). Голое число получает префикс p,
    иначе просто нижний регистр; итог сверяется с реальными id вызывающим."""
    s = str(raw).strip()
    return f"p{s}" if s.isdigit() else s.lower()


def _block_word(n):
    """Русское склонение «блок» под число попаданий — 1 блок, 2 блока, 5 блоков."""
    if n % 10 == 1 and n % 100 != 11:
        return "блок"
    if 2 <= n % 10 <= 4 and not 12 <= n % 100 <= 14:
        return "блока"
    return "блоков"


def _variant_counts(blocks, nav, request):
    """[(вариант, число попаданий)] — те же источники, что и _resolve (якоря
    Навигатора + дословные цитаты из текста правки), частоты через
    find.by_text. Вариант с нулём попаданий отбрасывается (найден не по
    тексту документа, а домыслен). Общая основа для _variant_inventory
    (строка для промпта Редактора-унификатора) и для _run_unify (Ф18-бис:
    вердикт проверяется по ЭТОМУ инвентарю, а не по списку пар модели —
    вариант, который модель не назвала, обязан пропасть из документа тоже)."""
    variants = _dedupe([_strip_anchor(a) for a in (nav.get("anchors") or [])] + _literals(request))
    counts = [(v, len(find.by_text(blocks, v))) for v in variants]
    return [(v, n) for v, n in counts if n > 0]


def _variant_inventory(blocks, nav, request):
    """Change 1 (Ф13): при дроблении на кластеры Редактор видит ОДИН кластер и
    "унифицирует" правку вида «выбери одно написание и поставь везде» к тому
    варианту, который уже стоит в этом кластере — он не знает, что есть
    другие. Инвентарь строится ОДИН раз до цикла кластеров и кладётся в
    начало фрагмента КАЖДОГО кластера. Если различных вариантов с
    попаданиями меньше двух — для одноцелевой правки это шум, возвращается "".
    """
    counts = _variant_counts(blocks, nav, request)
    if len(counts) < 2:
        return ""
    parts = ", ".join(f'«{v}» — {n} {_block_word(n)}' for v, n in counts)
    return f"Найдено в документе: {parts}"


def _resolve(blocks, nav, request):
    """id из Навигатора (провалидированные) + попадания по якорям + попадания
    по дословным цитатам («…», `…`, "…", "…") из текста правки — ВСЕ ТРИ
    источника объединяются и дедуплицируются, а не по очереди с откатом на
    следующий.

    Находка Ф8 (item C): цитата раньше искалась только как запасной путь,
    когда ids и anchors ничего не дали — а правки вида «сделай одинаково
    везде» (например №8: три разных написания года, каждое в «ёлочках»)
    Навигатор называет ОДНИМ id/anchor (первый случай, который увидел), и
    запасной путь никогда не срабатывал: ids были не пусты, а остальные
    случаи из документа терялись, фрагмент давал Редактору только один
    случай, и правка честно, но неверно отказывалась «в документе больше
    случаев нет». Цитата теперь всегда доливает свои совпадения.

    Люди цитируют документ неточно (тире вместо запятой и т.п.) — на двух
    приёмочных корпусах 11 таких якорей/цитат не находит ни точный, ни
    пробельно-гибкий поиск. Поэтому для каждого якоря и каждой цитаты по
    отдельности: если find.by_text не нашёл ни одного блока, в дело
    вступает find.locate (приблизительный поиск по токенам) — только как
    запасной путь для ЭТОГО якоря/цитаты, точные попадания find.by_text
    им не заменяются и остаются первыми.

    Пусто после всех источников — [] означает честный отказ выше, КРОМЕ
    одного случая (Ф19-бис, battery 20): position="end" от Навигатора — адрес
    задан позицией в документе, а не текстом («добавь раздел в конец
    документа»), цитировать здесь нечего по построению. Тогда, и только
    тогда, когда обычный резолв ничего не дал, последний блок документа сам
    становится адресом — Редактор получит его как соседа и сможет
    insert_after.

    В5: "pattern" от Навигатора — адрес по ОБРАЗЦУ, а не по цитате («даты
    приведи к формату ДД.ММ.ГГГГ» не цитируется, цитаты для формата не
    существует). find.by_regex собирает ВСЕ совпадения по документу тем же
    способом, каким якоря и цитаты собирают свои — не запасной путь, а
    равноправный источник id."""
    real_ids = {b["id"] for b in blocks}
    ids = [n for n in (_normalize_id(i) for i in (nav.get("ids") or [])) if n in real_ids]
    for anchor in nav.get("anchors") or []:
        anchor = _strip_anchor(anchor)
        ids += find.by_text(blocks, anchor) or find.locate(blocks, anchor)
    for quote in _literals(request):
        ids += find.by_text(blocks, quote) or find.locate(blocks, quote)
    if nav.get("pattern"):
        ids += _pattern_ids(blocks, nav["pattern"])
    ids = _dedupe(ids)
    if not ids and nav.get("position") == "end" and blocks:
        return [blocks[-1]["id"]]
    return ids


def _snapshot(doc):
    """Сохраняет документ во временный файл — точка отката ПЕРЕД применением."""
    fd, path = tempfile.mkstemp(suffix=".docx")
    os.close(fd)
    doc.save(path)
    return path


def _restore(snapshot_path):
    """Перечитывает документ из снимка. Возвращает НОВЫЕ (doc, idx): id из
    старого idx были ссылками на lxml-элементы прежнего дерева, их больше
    нет — вызывающий обязан взять из возврата, а не держать старый doc."""
    doc = Document(snapshot_path)
    idx = index(doc)
    os.remove(snapshot_path)
    return doc, idx


def _btext(b):
    return b["text"] if b["kind"] == "p" else " | ".join(c for row in b["rows"] for c in row)


def _is_heading(b):
    """Абзац — заголовок: структурный уровень (w:outlineLvl) или именованный
    стиль Heading*/Title (В1: см. _trace_error)."""
    if b.get("level") is not None:
        return True
    style = b.get("style") or ""
    return style.startswith("Heading") or style == "Title"


_TRACE_PRODUCING_OPS = {
    # В11 (находка Н66, «В1 инвертирован»): операции, СПОСОБНЫЕ оставить
    # заявленный trace — "heading" проверяется отдельно ниже (нужен ещё и
    # стиль операции, не только её имя).
    "table": {"create_table", "insert_row", "delete_row", "insert_col", "delete_col", "set_cell"},
    "list": {"set_list", "set_list_level"},
    "footnote": {"footnote"},
    "field": {"field"},
    "header_footer": {"set_header_footer"},
}
# Операции, способные ВНЕСТИ новый или переписанный текст, которым можно
# подделать структурный след (вписать «r0c0:...» вместо строки таблицы,
# поставить одинокий заголовок вместо настоящего раздела). Точечные правки
# существующего текста (replace_text/set_format/…) под эту категорию не
# попадают — ими нельзя «нарисовать» новую структуру, разве что исказить
# существующую, а это уже отдельный контроль (heading+text, список и т.д.).
_CONTENT_FORGE_OPS = {"insert_after", "insert_paragraphs", "create_table", "insert_row", "insert_col", "set_text"}


def _is_heading_style(style):
    return bool(style) and (style.startswith("Heading") or style == "Title")


def _trace_op_applied(trace, applied_ops):
    """True — среди РЕАЛЬНО применённых операций (не среди того, что Навигатор
    ЗАЯВИЛ в trace) есть хотя бы одна, способная оставить заявленный след.
    "heading" проверяется по стилю операции (set_style/insert_after/
    insert_paragraphs на Heading*/Title), "table" отдельно ловит "delete"
    целой таблицы (op.get("id") указывал на блок kind="t" в before)."""
    if trace == "heading":
        for op in applied_ops:
            name = op.get("op")
            if name in ("set_style", "insert_after") and _is_heading_style(op.get("style")):
                return True
            if name == "insert_paragraphs" and any(_is_heading_style(it.get("style")) for it in op.get("items") or []):
                return True
        return False
    return any(op.get("op") in _TRACE_PRODUCING_OPS.get(trace, ()) for op in applied_ops)


def _trace_error(trace, before, after, doc=None, applied_ops=()):
    """В1/В11 (находка Н66, «В1 инвертирован»): Проверяющий видит текстовый
    diff, и для него строка таблицы, ставшая абзацем со своей нотацией
    "r0c0:...", и настоящая строка таблицы неотличимы — обе выглядят как
    добавившийся текст с нужными словами. Раньше код проверял, СОВПАЛО ЛИ
    итоговое структурное состояние документа с ярлыком trace, который
    выдал Навигатор, — но Навигатор ошибается в классификации чаще, чем
    кажется (26B), и правки, реально выполненные ПРАВИЛЬНОЙ операцией,
    отказывались из-за чужой ошибки ярлыка (замер w18: `colbert#9`/`math#4`
    — реальный `set_style` на Heading１/2 отказан как "ни один абзац не стал
    заголовком", потому что абзац УЖЕ нёс `w:outlineLvl` до правки — код
    искал ПЕРЕХОД в heading, а не факт применения нужной операции; `colbert#16`
    — Навигатор наугад проставил trace=table абзацу с правкой формул, где
    таблицы вообще не было в деле). Это прямое нарушение инварианта 4
    (модель предлагает — код проверяет, а не наоборот).

    Починка: код смотрит на СДЕЛАННОЕ — какие операции реально применились
    (`applied_ops`), а не на итоговое состояние относительно ярлыка.
    Однозначная подпись подделки — trace заявлен, а НИ ОДНА применённая
    операция не способна его оставить (`_trace_op_applied`), И среди
    применённого есть операция, СПОСОБНАЯ подделать структуру текстом
    (`_CONTENT_FORGE_OPS` — insert_after/insert_paragraphs/set_text/…): это
    ровно форма обеих лжей прогона за рулём («нарисовать» строку/заголовок
    текстом вместо настоящей операции). Если ничего из «подделывающих»
    операций не применялось вовсе (например правка вообще не про trace —
    как `colbert#16`, где шли только replace_text по формулам) — заявленным
    классом просто нечего было подделать, отказывать не за что, ярлык
    Навигатора в этом случае действительно не имеет значения.

    Замкнутый словарь (Навигатор ограничен им в _NAV_PROMPT): null (правка
    без структурных ожиданий, доп. проверки нет), "table", "heading",
    "heading+text" (новый РАЗДЕЛ — заголовок И текст, минимум два новых
    абзаца — проверяется ПО-СТАРОМУ, через before/after, см. ниже: этого
    дефекта её логика не касалась), "list", "footnote", "field" (В2-бис),
    "header_footer" (В2-бис). Значение вне словаря не проверяется.

    Вызывается ДО Проверяющего (см. _finish) — несовпавший trace вообще не
    тратит вызов модели."""
    if not trace:
        return None

    if trace == "heading+text":
        # Единственная ветка, не задетая находкой Н66 — она и раньше смотрела
        # на НОВЫЕ абзацы (вставку раздела), а не на переход "стало героем"
        # относительно before, поэтому ложного отказа тут не было и менять
        # логику незачем (regression control: test_trace_heading_text_*).
        b_by_id = {b["id"]: b for b in before}
        a_by_id = {b["id"]: b for b in after}
        has_heading = has_body = False
        for i, blk in a_by_id.items():
            if blk["kind"] != "p" or i in b_by_id:
                continue  # интересуют только НОВЫЕ абзацы — раздел это вставка, не правка на месте
            if _is_heading(blk):
                has_heading = True
            elif blk["text"].strip():
                has_body = True
        if has_heading and has_body:
            return None
        return ("правка добавляет раздел (заголовок и текст, trace=heading+text), но в документе "
                "появился только заголовок без текста раздела (или наоборот) — новый раздел это "
                "минимум ДВА новых абзаца (insert_paragraphs), а не один")

    if trace not in ("table", "heading", "list", "footnote", "field", "header_footer"):
        return None

    if _trace_op_applied(trace, applied_ops):
        return None

    # "table"-исключение: целая таблица удалена операцией delete — это тоже
    # законный способ выполнить правку про таблицу, а "delete" сам по себе не
    # входит в _TRACE_PRODUCING_OPS (она удаляет ЛЮБОЙ блок, не только таблицы).
    if trace == "table":
        b_by_id = {b["id"]: b for b in before}
        if any(op.get("op") == "delete" and (b_by_id.get(op.get("id")) or {}).get("kind") == "t"
               for op in applied_ops):
            return None

    if not any(op.get("op") in _CONTENT_FORGE_OPS for op in applied_ops):
        # Среди применённого нет ничего, чем можно подделать структуру текстом
        # (только точечные правки существующего содержимого, например
        # replace_text по формулам) — заявленным классом нечего было
        # подделать, ярлык Навигатора здесь просто неточен, а не подделка.
        return None

    _REASONS = {
        "table": ("правка названа табличной (trace=table), но ни одна операция над таблицей не "
                  "применилась — похоже на подделку текстом вместо реальной правки таблицы"),
        "heading": ("правка названа заголовком раздела (trace=heading), но ни одна операция не "
                    "поставила абзацу стиль заголовка (Heading*/Title)"),
        "list": ("правка названа списочной (trace=list), но ни одна операция не изменила "
                 "принадлежность/уровень списка (numPr)"),
        "footnote": "правка названа сноской (trace=footnote), но сноска Word не была добавлена",
        "field": ("правка названа полем Word (trace=field), но поле (w:fldSimple/w:fldChar) не "
                  "было добавлено"),
        "header_footer": ("правка названа колонтитульной (trace=header_footer), но колонтитул не был "
                           "изменён отдельной операцией — похоже на подделку абзацем в теле документа"),
    }
    return _REASONS[trace]


def _struct_note(b, a):
    """Текст структурного отличия абзаца b→a (стиль/уровень/список/оформление
    ранов), или None. У таблиц структуры нет — там сравнивается только текст
    ячеек, это уже делает текстовое сравнение в _diff.

    Сравнение runs добавлено для set_format (Ф15): эта операция не трогает
    текст абзаца вообще, только b/i/u ранов — без сравнения runs diff видел
    бы такую правку как пустышку, а именно это уже было дефектом Ф11
    (set_style/move_after не давали diff и откатывались как "без изменений").

    Сравнение footnotes добавлено Ф19-бис: footnote не трогает ни текст, ни
    style/level/list/runs абзаца (w:footnoteReference — пустой для python-docx
    ран без w:t) — без счётчика правка терялась тем же способом, что раньше
    set_style/move_after. Сравнение fields — тот же приём для В2-бис: field
    (w:fldSimple/w:fldChar) тоже не меняет текст абзаца ни на символ."""
    if b["kind"] == "t" and a["kind"] == "t":
        # Начертание ячеек — единственная структура таблицы, которую умеет
        # менять операция (set_format по row/col); без этой ветки её результат
        # был невидим diff'у и правка не могла завершиться иначе как отказом.
        changed = [f"r{ri}c{ci}" for ri, (rb, ra) in enumerate(zip(b.get("fmt") or [], a.get("fmt") or []))
                   for ci, (cb, ca) in enumerate(zip(rb, ra)) if cb != ca]
        return f'оформление ячеек изменено ({", ".join(changed)})' if changed else None
    if b["kind"] != "p" or a["kind"] != "p":
        return None
    parts = []
    if b["style"] != a["style"]:
        parts.append(f'стиль «{b["style"]}» → «{a["style"]}»')
    if b.get("level") != a.get("level"):
        parts.append(f'уровень {b.get("level")} → {a.get("level")}')
    if b.get("list") != a.get("list"):
        parts.append(f'список {b.get("list")} → {a.get("list")}')
    if b.get("footnotes", 0) != a.get("footnotes", 0):
        parts.append(f'сносок {b.get("footnotes", 0)} → {a.get("footnotes", 0)}')
    if b.get("fields", 0) != a.get("fields", 0):
        parts.append(f'полей {b.get("fields", 0)} → {a.get("fields", 0)}')
    if b.get("runs") != a.get("runs"):
        old_fmt = ", ".join(_format_note(b.get("runs") or [])) or "без оформления"
        new_fmt = ", ".join(_format_note(a.get("runs") or [])) or "без оформления"
        parts.append(f'оформление «{old_fmt}» → «{new_fmt}»')
    return "; ".join(parts) if parts else None


def _move_note(before, after, a_by_id):
    """Запись diff'а на переместившийся блок, если множество id одинаково, а
    порядок отличается (move_after), иначе None. Переместившимся считается id
    с наибольшим сдвигом индекса — соседи, чья позиция сдвинулась заодно с
    ним на +-1, отдельной записи не получают (иначе на один move_after
    приходилось бы N записей вместо одной)."""
    order_before = [b["id"] for b in before]
    order_after = [b["id"] for b in after]
    if order_before == order_after:
        return None
    pos_before = {i: n for n, i in enumerate(order_before)}
    pos_after = {i: n for n, i in enumerate(order_after)}
    moved_id = max(pos_before, key=lambda i: abs(pos_before[i] - pos_after[i]))
    idx_after = pos_after[moved_id]
    after_id = order_after[idx_after - 1] if idx_after > 0 else None
    note = f"перемещён после {after_id}" if after_id else "перемещён в начало документа"
    text = _btext(a_by_id[moved_id])
    return {"id": moved_id, "before": text, "after": text, "note": note}


def _diff(before, after):
    """Блоки, у которых текст, стиль, уровень или список реально изменились,
    плюс исчезнувшие (delete) и появившиеся (insert_after/create_table) —
    только это видит Проверяющий, не документ целиком (инвариант 3 из
    CLAUDE.md).

    Раньше сравнивался только _btext — set_style и move_after были невидимы
    diff'у, Проверяющий получал пустой список изменений и run_edit откатывал
    правку с "текст не изменился", хотя структура реально поменялась. Теперь
    блоки сравниваются целиком (текст + style/level/list), а перестановка
    блоков детектируется отдельно (_move_note) — только когда МНОЖЕСТВО id до
    и после одинаково (иначе это insert_after/delete, не move), чтобы не
    плодить ложные записи о перемещении там, где на деле что-то вставили или
    удалили."""
    b_by_id = {b["id"]: b for b in before}
    a_by_id = {b["id"]: b for b in after}

    changed = []
    for i, blk in a_by_id.items():
        bb = b_by_id.get(i)
        text_before = _btext(bb) if bb else ""
        text_after = _btext(blk)
        note = _struct_note(bb, blk) if bb else None
        if bb is None or text_before != text_after or note:
            rec = {"id": i, "before": text_before, "after": text_after}
            if bb is None:
                # Тот же дефект, что у delete, с другой стороны: новый блок шёл
                # как «было 0 зн. «» стало N зн.» — Проверяющий не видел ни того,
                # что блок НОВЫЙ, ни его стиля, и не мог судить правку «добавь
                # раздел» (заголовок + текст) вообще ничем, кроме текста.
                rec["inserted"] = True
                rec["note"] = (f'стиль «{blk["style"]}»' if blk["kind"] == "p"
                               else f'таблица {len(blk.get("rows") or [])} строк')
            elif note:
                rec["note"] = note
            changed.append(rec)
    # Прогон за рулём 2026-07-30: удалённый блок отдавался Проверяющему как
    # «было N зн. «…» стало 0 зн. «»» — ровно та форма, которую _CHECK_PROMPT
    # велит считать обрубленным текстом. Сжатие раздела через delete из-за
    # этого откатывалось (m16 замера w21: «Текст обрублен… удалён полностью
    # (стало 0 зн.)»). Удаление называется удалением, судить его по существу.
    changed += [{"id": i, "before": _btext(b), "after": "", "deleted": True}
                for i, b in b_by_id.items() if i not in a_by_id]

    if set(b_by_id) == set(a_by_id):
        move = _move_note(before, after, a_by_id)
        if move:
            existing = next((c for c in changed if c["id"] == move["id"]), None)
            if existing:
                existing["note"] = f'{existing["note"]}; {move["note"]}' if existing.get("note") else move["note"]
            else:
                changed.append(move)
    return changed


